export const legacyServants: ServantDefinition[] = rows.map(
  (
    [trueName, tags, traits, wishes, _unused, alignment, npName, npType],
    index,
  ) => {
    const rarity = 5 - Math.floor(index / 7),
      range = balance.rarityRanges[rarity - 1];
    const fraction = ((index * 37 + 17) % 101) / 100;
    const budget = Math.round(
      range.baq[0] + (range.baq[1] - range.baq[0]) * fraction,
    );
    const strengths = [0.43 + (index % 3) * 0.02, 0.32, 0];
    strengths[2] = 1 - strengths[0] - strengths[1];
    const values = strengths.map((s) => Math.round(budget * s));
    const order = index % 3;
    return {
      id: trueName
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-"),
      trueName,
      class: classes[index % 7],
      rarity,
      maxHp: Math.round(range.hp[0] + (range.hp[1] - range.hp[0]) * fraction),
      buster: values[order],
      arts: values[(order + 1) % 3],
      quick: values[(order + 2) % 3],
      manaEfficiency: 1 + ((index * 13) % 17) / 10,
      mystery: 15 + ((index * 19) % 86),
      noblePhantasm: {
        name: npName,
        type: npType,
        power: 1.9 + (index % 5) * 0.05,
      },
      summoning: {
        tags: tags.split(" "),
        desiredTraits: traits.split(" "),
        wishAffinities: wishes.split(" "),
        alignment,
      },
    };
  },
);

// A ordem e os números do catálogo original são preservados para replays antigos.
export const servants: ServantDefinition[] = [...legacyServants, ...additions];
