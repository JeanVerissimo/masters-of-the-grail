export const additions: ServantDefinition[] = profiles.map(
  (
    [
      trueName,
      servantClass,
      rarity,
      tags,
      traits,
      wishes,
      alignment,
      npName,
      npType,
    ],
    index,
  ) => {
    const range = balance.rarityRanges[rarity - 1];
    const fraction = ((index * 37 + 29) % 101) / 100;
    const budget = Math.round(
      range.baq[0] + (range.baq[1] - range.baq[0]) * fraction,
    );
    const primary = Math.round(budget * 0.44),
      secondary = Math.round(budget * 0.32),
      tertiary = budget - primary - secondary;
    const stats =
      npType === "BUSTER"
        ? [primary, secondary, tertiary]
        : npType === "ARTS"
          ? [tertiary, primary, secondary]
          : [secondary, tertiary, primary];
    return {
      id: trueName
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-"),
      trueName,
      class: servantClass,
      rarity,
      maxHp: Math.round(range.hp[0] + (range.hp[1] - range.hp[0]) * fraction),
      buster: stats[0],
      arts: stats[1],
      quick: stats[2],
      manaEfficiency: 1 + ((index * 7) % 17) / 10,
      mystery: 15 + ((index * 19 + 31) % 86),
      noblePhantasm: {
        name: npName,
        type: npType,
        power: 1.9 + (index % 5) * 0.05,
      },
      summoning: {
        tags: tags.split(" "),
        desiredTraits: traits.split(" "),
        wishAffinities: wishes.split(" "),
        alignment,
      },
    };
  },
);
